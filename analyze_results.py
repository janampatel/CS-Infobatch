def _roc_auc(labels: np.ndarray, probs: np.ndarray, n_thresholds: int = 300):
    """
    Compute ROC curve + AUC via threshold sweep.
    Returns (fpr, tpr, auc_val).
    Uses random subsample of n_thresholds evenly-spaced thresholds.
    """
    thresholds = np.linspace(1.0, 0.0, n_thresholds)
    pos = labels == 1
    neg = ~pos
    n_pos = pos.sum()
    n_neg = neg.sum()
    if n_pos == 0 or n_neg == 0:
        return np.array([0, 1]), np.array([0, 1]), 0.5

    fpr_list, tpr_list = [1.0], [1.0]
    for t in thresholds:
        pred = probs >= t
        tp = (pred & pos).sum()
        fp = (pred & neg).sum()
        fpr_list.append(fp / n_neg)
        tpr_list.append(tp / n_pos)
    fpr_list.append(0.0)
    tpr_list.append(0.0)

    fpr = np.array(fpr_list)
    tpr = np.array(tpr_list)
    # Sort by fpr ascending for trapezoidal integration
    order = np.argsort(fpr)
    fpr, tpr = fpr[order], tpr[order]
    auc_val = float(np.trapezoid(tpr, fpr) if hasattr(np, "trapezoid") else np.trapz(tpr, fpr))
    return fpr, tpr, auc_val


def _calibration_curve(labels: np.ndarray, probs: np.ndarray,
                        n_bins: int = 15, strategy: str = "uniform"):
    """
    Returns (mean_pred_prob, frac_pos) for filled bins (>= 50 samples).
    strategy: 'uniform' = equal-width bins; 'quantile' = equal-frequency bins.
    """
    if strategy == "quantile":
        edges = np.percentile(probs, np.linspace(0, 100, n_bins + 1))
        edges = np.unique(edges)
    else:
        edges = np.linspace(0.0, 1.0, n_bins + 1)

    mean_pred, frac_pos = [], []
    for i in range(len(edges) - 1):
        mask = (probs >= edges[i]) & (probs < edges[i + 1])
        if mask.sum() >= 50:
            mean_pred.append(probs[mask].mean())
            frac_pos.append(labels[mask].mean())
    return np.array(mean_pred), np.array(frac_pos)

