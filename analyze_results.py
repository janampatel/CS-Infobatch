    n = len(RATIOS)
    fig, axes = plt.subplots(1, n, figsize=(5 * n, 5))
    if n == 1: axes = [axes]
    fig.suptitle("ROC Curves by Prune Ratio  (pixel-level, tree class)", fontsize=13)

